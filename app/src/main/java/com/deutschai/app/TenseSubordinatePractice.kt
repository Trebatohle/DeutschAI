internal fun buildTenseSubordinateQuestions(level: String? = null): List<ReviewQuestion> {
    require(level == null || level in setOf("A2", "B1")) {
        "Tense and subordinate-clause practice is only defined for A2 and B1."
    }
    return tenseSubordinateItems.asSequence()
        .filter { level == null || it.level == level }
        .map { item ->
            require(item.choices.size == 4 && item.choices.distinct().size == 4) {
                "Invalid options in ${item.id}"
            }
            require(item.correctAnswer in item.choices) { "Missing correct answer in ${item.id}" }
            ReviewQuestion(
                id = stableReviewId("tense-subordinate", item.level, item.id),
                sourceKind = "wordtools",
                sourceTitle = "${item.level} · ${item.section}",
                prompt = item.prompt,
                choices = item.choices,
                correctIndex = item.choices.indexOf(item.correctAnswer),
                explanation = item.explanation,
                germanSentence = item.germanSentence,
                translation = item.translation,
                cefrLevel = item.level,
                focusTopicId = "grammar:${item.level.lowercase()}:${item.areaId}",
                focusTopicTitle = item.areaTitle,
                focusTerm = item.focusTerm
            )
        }
        .toList()
}
